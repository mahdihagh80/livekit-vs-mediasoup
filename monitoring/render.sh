#!/usr/bin/env bash
# Writes the bench Prometheus config from bench.yaml (hosts, ports, monitoring.*):
#   monitoring/prometheus/prometheus.yml   scrape targets
#   monitoring/prometheus/args             Prometheus command line (listen, retention)
# Used by start-prometheus.sh (native) and the docker "monitoring" profile.
# No Grafana runs on the bench hosts: see monitoring/view-local.sh.
source "$(dirname "$0")/../host/lib.sh"
DIR="$BENCH_ROOT/monitoring"

gen_targets() { for g in $GEN_IPS; do printf "'%s:%s'," "$g" "$1"; done | sed 's/,$//'; }
lk_targets() { for i in $(seq 0 7); do printf "'%s:%s'," "$SFU_IP" $((LK_METRICS_BASE + i)); done | sed 's/,$//'; }

mkdir -p "$DIR/prometheus"
cat >"$DIR/prometheus/prometheus.yml" <<EOF
# generated by monitoring/render.sh from bench.yaml; edit bench.yaml, not this file
global:
  scrape_interval: $PROM_SCRAPE
  evaluation_interval: $PROM_SCRAPE
scrape_configs:
  - job_name: node            # SFU host
    static_configs: [{targets: ['$SFU_IP:$NODE_EXPORTER_PORT'], labels: {role: sfu}}]
  - job_name: node-gen        # generator hosts
    static_configs: [{targets: [$(gen_targets "$NODE_EXPORTER_PORT")], labels: {role: gen}}]
  - job_name: loadgen
    static_configs: [{targets: [$(gen_targets "$AGENT_PORT")]}]
  - job_name: livekit         # up to 8 instances; down targets are fine
    static_configs: [{targets: [$(lk_targets)]}]
  - job_name: mediasoup
    static_configs: [{targets: ['$SFU_IP:$MS_METRICS_PORT', '$SFU_IP:$MS_SIG_METRICS_PORT']}]
EOF

# One argument per line, read by the container's `sh -c` wrapper.
# admin-api: monitoring/export.sh takes TSDB snapshots through it (loopback only by default).
cat >"$DIR/prometheus/args" <<EOF
--config.file=/etc/prometheus/prometheus.yml
--storage.tsdb.path=/prometheus
--storage.tsdb.retention.time=$PROM_RETENTION
--web.listen-address=$PROM_LISTEN
--web.enable-admin-api
EOF

case $PROM_LISTEN in
  127.*|localhost:*) ;;
  *) echo "WARN: Prometheus will listen on $PROM_LISTEN (not loopback), admin API included. Firewall it, or set monitoring.prometheus_url to http://127.0.0.1:<port>." >&2 ;;
esac
echo "monitoring config written (prometheus $PROM_LISTEN, retention $PROM_RETENTION)"

# Metrics gateway (every generator, compose service metrics-gw): this host's
# loadgen and node_exporter behind one port, for a scraper that can reach only
# that port (the SFU host's HAProxy forwards to it). Only these two paths answer.
GW_IP=$(my_ip); [[ $GW_IP == 127.0.0.1 ]] && GW_IP=""
mkdir -p "$DIR/gen-gw"
cat >"$DIR/gen-gw/haproxy.cfg" <<EOF
# generated by monitoring/render.sh from bench.yaml; edit bench.yaml, not this file
global
    log stdout format raw local0 warning
defaults
    mode http
    log global
    timeout connect 2s
    timeout client 30s
    timeout server 30s
frontend metrics
    bind $GW_IP:$GEN_GW_PORT
    http-request deny deny_status 404 unless METH_GET { path /loadgen/metrics /node/metrics }
    use_backend loadgen if { path /loadgen/metrics }
    default_backend node
backend loadgen          # loadgen.monitoring_port: answers only while a run is in progress (else 503)
    http-request set-path /metrics
    server loadgen 127.0.0.1:$AGENT_PORT
backend node
    http-request set-path /metrics
    server node 127.0.0.1:$NODE_EXPORTER_PORT
EOF
echo "metrics gateway config written (${GW_IP:-*}:$GEN_GW_PORT -> loadgen :$AGENT_PORT, node :$NODE_EXPORTER_PORT)"
